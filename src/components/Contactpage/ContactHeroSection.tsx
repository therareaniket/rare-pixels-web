export default function ContactHeroSection() {

    const waveSvgRef = useRef<SVGSVGElement | null>(null);
    const mobileWaveSvgRef = useRef<SVGSVGElement | null>(null);

    useLayoutEffect(() => {
        const mainSvgElement = waveSvgRef.current;
        const mobileSvgElement = mobileWaveSvgRef.current;

        if (!mainSvgElement || !mobileSvgElement) return;

        const mobileMedia = window.matchMedia("(max-width: 479px)");
        const reducedMotionMedia = window.matchMedia(
            "(prefers-reduced-motion: reduce)"
        );

        let ctx: gsap.Context | null = null;

        type WavePoint = {
            x: number;
            y: number;
            originalY: number;
        };

        type AnimatedWave = {
            path: SVGPathElement;
            points: WavePoint[];
            amplitude: number;
            wavelength: number;
        };

        const buildSmoothPath = (points: WavePoint[]) => {
            if (points.length < 2) return "";

            let pathData = `M ${points[0].x} ${points[0].y}`;

            for (
                let index = 1;
                index < points.length - 1;
                index++
            ) {
                const currentPoint = points[index];
                const nextPoint = points[index + 1];

                const middleX =
                    (currentPoint.x + nextPoint.x) / 2;

                const middleY =
                    (currentPoint.y + nextPoint.y) / 2;

                pathData +=
                    ` Q ${currentPoint.x} ${currentPoint.y}` +
                    ` ${middleX} ${middleY}`;
            }

            const lastPoint = points[points.length - 1];

            pathData += ` T ${lastPoint.x} ${lastPoint.y}`;

            return pathData;
        };

        const resetAnimatedPaths = (
            svgElement: SVGSVGElement
        ) => {
            const sourcePaths = Array.from(
                svgElement.querySelectorAll<SVGPathElement>(
                    ".contact-wave-source"
                )
            );

            const animatedPaths = Array.from(
                svgElement.querySelectorAll<SVGPathElement>(
                    ".contact-wave-animated"
                )
            );

            sourcePaths.forEach((sourcePath, index) => {
                const animatedPath = animatedPaths[index];

                if (!animatedPath) return;

                const originalPathData =
                    sourcePath.getAttribute("d");

                if (originalPathData) {
                    animatedPath.setAttribute(
                        "d",
                        originalPathData
                    );
                }
            });
        };

        const createAnimatedWaves = (
            svgElement: SVGSVGElement,
            isExtraMobileSvg: boolean
        ): AnimatedWave[] => {
            const sourcePaths = Array.from(
                svgElement.querySelectorAll<SVGPathElement>(
                    ".contact-wave-source"
                )
            );

            const animatedPaths = Array.from(
                svgElement.querySelectorAll<SVGPathElement>(
                    ".contact-wave-animated"
                )
            );

            return sourcePaths
                .map((sourcePath, pathIndex) => {
                    const animatedPath =
                        animatedPaths[pathIndex];

                    if (!animatedPath) return null;

                    const totalLength =
                        sourcePath.getTotalLength();

                    if (!Number.isFinite(totalLength)) {
                        return null;
                    }

                    if (totalLength <= 0) {
                        return null;
                    }

                    const searchSteps = 500;

                    const startingPoint =
                        sourcePath.getPointAtLength(0);

                    let maximumHorizontalDistance = 0;
                    let firstEdgeLength = totalLength;

                    for (
                        let searchIndex = 0;
                        searchIndex <= searchSteps;
                        searchIndex++
                    ) {
                        const searchProgress =
                            searchIndex / searchSteps;

                        const searchLength =
                            searchProgress * totalLength;

                        const searchPoint =
                            sourcePath.getPointAtLength(
                                searchLength
                            );

                        const horizontalDistance =
                            Math.abs(
                                searchPoint.x -
                                startingPoint.x
                            );

                        if (
                            horizontalDistance >
                            maximumHorizontalDistance
                        ) {
                            maximumHorizontalDistance =
                                horizontalDistance;

                            firstEdgeLength =
                                searchLength;
                        }
                    }

                    if (firstEdgeLength <= 0) {
                        firstEdgeLength = totalLength;
                    }

                    const numberOfPoints =
                        isExtraMobileSvg
                            ? 100
                            : mobileMedia.matches
                                ? 120
                                : 180;

                    const points: WavePoint[] =
                        Array.from(
                            {
                                length: numberOfPoints,
                            },
                            (_, pointIndex) => {
                                const progress =
                                    pointIndex /
                                    (numberOfPoints - 1);

                                const pointLength =
                                    firstEdgeLength *
                                    progress;

                                const svgPoint =
                                    sourcePath.getPointAtLength(
                                        pointLength
                                    );

                                return {
                                    x: svgPoint.x,
                                    y: svgPoint.y,
                                    originalY: svgPoint.y,
                                };
                            }
                        );

                    const amplitude =
                        isExtraMobileSvg
                            ? 55
                            : mobileMedia.matches
                                ? 45
                                : window.innerWidth < 1200
                                    ? 32
                                    : 24;

                    const wavelength =
                        isExtraMobileSvg
                            ? 2.2
                            : mobileMedia.matches
                                ? 2.4
                                : 2.8;

                    return {
                        path: animatedPath,
                        points,
                        amplitude,
                        wavelength,
                    };
                })
                .filter(
                    (
                        wave
                    ): wave is AnimatedWave =>
                        wave !== null
                );
        };

        const createWaveAnimation = () => {
            if (ctx) {
                ctx.revert();
                ctx = null;
            }

            resetAnimatedPaths(mainSvgElement);
            resetAnimatedPaths(mobileSvgElement);

            if (reducedMotionMedia.matches) {
                return;
            }

            ctx = gsap.context(() => {
                const animatedWaves =
                    createAnimatedWaves(
                        mainSvgElement,
                        false
                    );

                if (mobileMedia.matches) {
                    animatedWaves.push(
                        ...createAnimatedWaves(
                            mobileSvgElement,
                            true
                        )
                    );
                }

                if (animatedWaves.length === 0) {
                    return;
                }

                const animationState = {
                    progress: 0,
                };

                const updateAllWaves = () => {
                    const phase =
                        animationState.progress *
                        Math.PI *
                        2;

                    animatedWaves.forEach((wave) => {
                        const totalPoints =
                            wave.points.length;

                        wave.points.forEach(
                            (point, pointIndex) => {
                                const pointProgress =
                                    pointIndex /
                                    (totalPoints - 1);

                                const pointPhase =
                                    pointProgress *
                                    Math.PI *
                                    wave.wavelength;

                                point.y =
                                    point.originalY +
                                    Math.sin(
                                        pointPhase - phase
                                    ) *
                                    wave.amplitude;
                            }
                        );

                        wave.path.setAttribute(
                            "d",
                            buildSmoothPath(wave.points)
                        );
                    });
                };

                updateAllWaves();

                gsap.fromTo(
                    animationState,
                    {
                        progress: 0,
                    },
                    {
                        progress: 1,
                        duration: 5,
                        ease: "none",
                        repeat: -1,
                        onUpdate: updateAllWaves,
                    }
                );
            });
        };

        createWaveAnimation();

        mobileMedia.addEventListener(
            "change",
            createWaveAnimation
        );

        reducedMotionMedia.addEventListener(
            "change",
            createWaveAnimation
        );

        return () => {
            mobileMedia.removeEventListener(
                "change",
                createWaveAnimation
            );

            reducedMotionMedia.removeEventListener(
                "change",
                createWaveAnimation
            );

            if (ctx) {
                ctx.revert();
                ctx = null;
            }

            resetAnimatedPaths(mainSvgElement);
            resetAnimatedPaths(mobileSvgElement);
        };
    }, []);

    return (
        <>
            <section id="first-section" className="contact-hero-section">
                <div className="container">
                    <div className="contact-hero-wrapper">
                        <h1 className="contact-hero-title text-sb">Tell Us What You Need. We Know How To Build.</h1>

                        <div className="contact-hero-image">
                            <Image src="/images/contactpage/contacthero/contact-hero-image.svg" alt="contact-hero" width={560} height={485}></Image>
                        </div>

                        <svg
                            ref={waveSvgRef}
                            className="cnct-hero-bg-image"
                            viewBox="0 0 1920 585"
                            preserveAspectRatio="xMidYMid meet"
                            fill="none"
                            xmlns="http://www.w3.org/2000/svg"
                            aria-hidden="true"
                        >
                            <g opacity="0.1">
                                {wavePaths.map((path, index) => (
                                    <g key={`contact-wave-${index}`}>
                                        <path
                                            className="contact-wave-source"
                                            d={path}
                                            fill="none"
                                            stroke="none"
                                            visibility="hidden"
                                            pointerEvents="none"
                                        />

                                        <path
                                            className="contact-wave-animated"
                                            d={path}
                                            fill="none"
                                            stroke="black"
                                            strokeWidth="2"
                                            strokeLinecap="round"
                                            strokeLinejoin="round"
                                        />
                                    </g>
                                ))}
                            </g>
                        </svg>

                        <svg
                            ref={mobileWaveSvgRef}
                            className="cnct-hero-bg-image-for-mobile"
                            viewBox="0 0 1920 339"
                            preserveAspectRatio="xMidYMid meet"
                            fill="none"
                            xmlns="http://www.w3.org/2000/svg"
                            aria-hidden="true"
                        >
                            <g opacity="0.1">
                                {mobileWavePaths.map((path, index) => (
                                    <g key={`mobile-contact-wave-${index}`}>
                                        <path
                                            className="contact-wave-source"
                                            d={path}
                                            fill="none"
                                            stroke="none"
                                            visibility="hidden"
                                            pointerEvents="none"
                                        />

                                        <path
                                            className="contact-wave-animated"
                                            d={path}
                                            fill="none"
                                            stroke="black"
                                            strokeWidth="2"
                                            strokeLinecap="round"
                                            strokeLinejoin="round"
                                        />
                                    </g>
                                ))}
                            </g>
                        </svg>
                    </div>
                </div>
            </section>
        </>
    );
}